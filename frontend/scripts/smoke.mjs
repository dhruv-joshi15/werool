import { chromium } from '@playwright/test'
import assert from 'node:assert/strict'
const browser=await chromium.launch({headless:true})
const page=await browser.newPage({viewport:{width:1440,height:1050}})
const errors=[]
page.on('pageerror',e=>errors.push(e.message))
try {
 const origin=process.argv[2]||process.env.FRONTEND_URL||'http://localhost:5173'
 await page.goto(origin)
 const health=await page.request.get(`${origin}/api/v1/health`)
 assert.equal(health.status(),200)
 assert.equal((await health.json()).dataset_ready,true)
 const docs=await page.request.get(`${origin}/docs`)
 assert.ok((await docs.text()).includes('swagger-ui'))
 await page.getByRole('heading',{name:'Forecast meets reality'}).waitFor()
 await page.getByText('period MAE',{exact:true}).waitFor()
 await page.screenshot({path:'/tmp/wind-desk-desktop.png',fullPage:true})
 assert.equal(await page.locator('.metric-grid .metric').count(),4)
 await page.locator('#decision-date').fill('2026-01-31')
 await page.getByText('1 Feb 2026',{exact:true}).first().waitFor()
 await page.getByRole('button',{name:'Decision explorer',exact:true}).click()
 await page.getByRole('heading',{name:'The forecast available to you'}).waitFor()
 assert.equal(await page.getByRole('columnheader',{name:'Actual · MW',exact:true}).count(),0)
 assert.equal(await page.locator('.legend').getByText('Actual',{exact:true}).count(),0)
 const downloadPromise=page.waitForEvent('download')
 await page.getByRole('button',{name:'Export day'}).click()
 const download=await downloadPromise
 assert.ok(download.suggestedFilename().includes('2026-01-31'))
 await page.locator('#cutoff').fill('04:30')
 await page.getByRole('button',{name:'Apply',exact:true}).click()
 await page.getByText('As of 04:30',{exact:true}).waitFor()
 await page.getByRole('heading',{name:'The forecast available to you'}).waitFor()
 await page.getByRole('button',{name:'Accuracy trends',exact:true}).click()
 await page.getByRole('heading',{name:'Daily accuracy',exact:true}).waitFor()
 assert.equal(await page.locator('.metric-grid .metric').count(),4)
 await page.getByRole('button',{name:'Forecast vintages',exact:true}).click()
 await page.getByRole('heading',{name:'Publication history',exact:true}).waitFor()
 await page.getByRole('button',{name:'Data & methodology',exact:true}).click()
 await page.getByRole('heading',{name:'Built on Elexon. Grounded in time.'}).waitFor()
 await page.screenshot({path:'/tmp/wind-desk-methodology.png',fullPage:true})
 await page.setViewportSize({width:390,height:844})
 await page.getByRole('button',{name:'Open navigation',exact:true}).click()
 await page.getByRole('button',{name:'Overview',exact:true}).click()
 await page.getByRole('heading',{name:'Forecast meets reality'}).waitFor()
 await page.screenshot({path:'/tmp/wind-desk-mobile.png',fullPage:true})
 assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth<=window.innerWidth),'Mobile page overflows horizontally')
 // Verify network failures are explicit and can recover, with no fabricated values.
 await page.route('**/api/v1/evaluation?**',r=>r.fulfill({status:503,contentType:'application/json',body:JSON.stringify({detail:'Snapshot unavailable'})}))
 await page.getByRole('button',{name:'Next decision day',exact:true}).count().then(async()=>{
   await page.getByRole('button',{name:'Previous decision day',exact:true}).click()
 })
 await page.getByRole('heading',{name:'We couldn’t load the data'}).first().waitFor()
 await page.unroute('**/api/v1/evaluation?**')
 await page.getByRole('button',{name:'Try again',exact:true}).first().click()
 await page.getByRole('heading',{name:'Forecast meets reality'}).waitFor()
 assert.deepEqual(errors,[])
 console.log('PASS: real API, all five views, Jan 31 boundary, decision outcome isolation, cutoff apply, CSV download, mobile navigation/layout, error and retry. No browser errors.')
} finally {await browser.close()}
